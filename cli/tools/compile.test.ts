import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { spawnSync } from 'node:child_process'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const cli = join(import.meta.dirname, '..')

// The binary is what users install: it has no repository beside it to read the scaffold templates or the ai/ pack from.
describe('the compiled binary', () => {
  let dir: string
  let binary: string
  let metafile: string

  beforeAll(async () => {
    dir = await mkdtemp(join(tmpdir(), 'caffeine-compile-'))
    binary = join(dir, 'caffeine')
    metafile = join(dir, 'meta.json')
    const compiled = spawnSync(
      process.execPath,
      [join(import.meta.dirname, 'compile.ts'), '--outfile', binary, '--metafile', metafile],
      { cwd: cli, encoding: 'utf8' },
    )
    expect(compiled.stderr).toBe('')
    expect(compiled.status).toBe(0)
  }, 60_000)

  afterAll(async () => {
    await rm(dir, { recursive: true, force: true })
  })

  test('prints the version of the package it was compiled from, which tells an installed binary apart', async () => {
    const { version } = JSON.parse(await readFile(join(cli, 'package.json'), 'utf8'))

    const result = spawnSync(binary, ['--version'], { encoding: 'utf8' })

    expect(result.stderr).toBe('')
    expect(result.status).toBe(0)
    expect(result.stdout).toBe(`${version}\n`)
  })

  test('scaffolds a project, its agent files included, from what it embeds', async () => {
    const result = spawnSync(binary, ['scaffold', 'demo', '--arch', 'usecase'], { cwd: dir, encoding: 'utf8' })

    expect(result.stderr).toBe('')
    expect(result.status).toBe(0)

    const template = join(cli, 'command', 'scaffold', 'templates', 'http', 'usecase')
    const ai = join(cli, '..', 'ai')
    const project = join(dir, 'demo')
    const copies = [
      [join(project, '.caffeinerc.ts'), join(template, '.caffeinerc.ts')],
      [join(project, 'src', 'main.ts'), join(template, 'src', 'main.ts')],
      [join(project, 'AGENTS.md'), join(ai, 'templates', 'AGENTS.md')],
      [
        join(project, '.agents', 'skills', 'caffeine-http-controller', 'SKILL.md'),
        join(ai, 'skills', 'caffeine-http-controller', 'SKILL.md'),
      ],
    ]
    for (const [copy, source] of copies) {
      expect(await readFile(copy, 'utf8')).toBe(await readFile(source, 'utf8'))
    }
    expect(JSON.parse(await readFile(join(project, 'package.json'), 'utf8'))).toMatchObject({ name: 'demo' })
  })

  // A release builds each platform package's SBOM from this list: a bundled file missing from it is a package the SBOM
  // leaves out.
  test('lists every file it bundles, from the CLI and from its dependencies', async () => {
    const inputs = Object.keys(JSON.parse(await readFile(metafile, 'utf8')).inputs)

    expect(inputs).toContain('bin.ts')
    expect(
      inputs.filter(input => input.startsWith('../node_modules/')).map(input => input.split('/').slice(2, 4).join('/')),
    ).toContain('@sinclair/typebox')
  })

  // `.caffeinerc.ts` imports `defineConfig` from the project's own `@caffeinejs/cli`, which an install lays out the way
  // this stand-in is: an `exports` map into `dist/`, and nothing at the package root to fall back on.
  test('loads a config that imports @caffeinejs/cli from the project node_modules', async () => {
    const project = join(dir, 'generated')
    expect(spawnSync(binary, ['scaffold', 'generated', '--arch', 'usecase'], { cwd: dir }).status).toBe(0)
    const installed = join(project, 'node_modules', '@caffeinejs', 'cli')
    await mkdir(join(installed, 'dist'), { recursive: true })
    await writeFile(
      join(installed, 'package.json'),
      JSON.stringify({ name: '@caffeinejs/cli', type: 'module', exports: { '.': './dist/index.js' } }),
    )
    await writeFile(join(installed, 'dist', 'index.js'), 'export const defineConfig = config => config\n')

    const result = spawnSync(binary, ['generate', 'modules', '--cwd', project], { encoding: 'utf8' })

    expect(result.stderr).toBe('')
    expect(result.status).toBe(0)
    expect(await readFile(join(project, 'src', 'root.gen.mod.ts'), 'utf8')).toStartWith(
      '// AUTO-GENERATED by @caffeinejs/cli',
    )
  })
})

// A release compiles every binary from the Bun runtime it pinned, never one Bun downloads.
test('compiles from the Bun runtime it is given', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'caffeine-compile-'))
  try {
    const result = spawnSync(
      process.execPath,
      [
        join(import.meta.dirname, 'compile.ts'),
        '--outfile',
        join(dir, 'caffeine'),
        '--executable-path',
        join(dir, 'missing'),
      ],
      { encoding: 'utf8' },
    )

    expect(result.status).toBe(1)
    expect(result.stderr).toContain('executablePath must be a valid path to a Bun executable')
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})
