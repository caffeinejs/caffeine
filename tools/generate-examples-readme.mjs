#!/usr/bin/env node

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const examplesDir = resolve(dirname(fileURLToPath(import.meta.url)), '../examples')
const readmePath = join(examplesDir, 'README.md')
const startMarker = '<!-- examples:start -->'
const endMarker = '<!-- examples:end -->'

const examples = readdirSync(examplesDir, { withFileTypes: true })
  .flatMap(entry => {
    const match = /^(\d+)-/.exec(entry.name)
    return entry.isDirectory() && match ? [{ directory: entry.name, number: Number(match[1]) }] : []
  })
  .sort((a, b) => a.number - b.number || a.directory.localeCompare(b.directory))
  .map(example => {
    const packagePath = join(examplesDir, example.directory, 'package.json')
    const manifest = JSON.parse(readFileSync(packagePath, 'utf8'))
    if (
      typeof manifest.name !== 'string' ||
      !manifest.name.trim() ||
      typeof manifest.description !== 'string' ||
      !manifest.description.trim()
    ) {
      throw new Error(`${packagePath} must define non-empty string fields "name" and "description"`)
    }
    return `${example.number}. [${manifest.name}](${example.directory}): ${manifest.description}`
  })

const readme = readFileSync(readmePath, 'utf8')
const start = readme.indexOf(startMarker)
const end = readme.indexOf(endMarker)
if (
  start === -1 ||
  end === -1 ||
  end < start ||
  readme.indexOf(startMarker, start + 1) !== -1 ||
  readme.indexOf(endMarker, end + 1) !== -1
) {
  throw new Error(`${readmePath} must contain one ordered pair of table-of-contents markers`)
}

const generated = `${startMarker}\n<!-- Generated by \`make examples-readme\`; do not edit. -->\n${examples.join('\n')}\n${endMarker}`
writeFileSync(readmePath, `${readme.slice(0, start)}${generated}${readme.slice(end + endMarker.length)}`)
